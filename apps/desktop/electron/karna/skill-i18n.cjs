function translateCategory(category) {
  return SKILL_CATEGORY_ZH[category] || category
}

function translateSkillName(name) {
  if (SKILL_NAME_ZH[name]) return SKILL_NAME_ZH[name]
  return name
}

function generateDefaultDesc(name) {
  const readableName = name.replace(/[-_]/g, ' ')
  return `技能：${readableName}`
}

function translateSkillDescription(name, originalDesc) {
  if (SKILL_DESC_ZH[name]) {
    return SKILL_DESC_ZH[name]
  }
  if (originalDesc && originalDesc.trim() && originalDesc !== '>-' && originalDesc !== '|') {
    if (/^[\x00-\x7F\s\p{P}]*$/.test(originalDesc) && /[a-zA-Z]/.test(originalDesc)) {
      return originalDesc
    }
    return originalDesc
  }
  return generateDefaultDesc(name)
}

